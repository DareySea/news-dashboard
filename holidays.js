// «День военного топографа», «День геолога»: последнее слово — профессия в родительном падеже
const profWord = t => /(ист|ик|ог|ер|ёр|ор|тел|щик|чик|ник|ар|ант|ент|граф|вед|мейстер|ург|ном|лог|ач|ец|яр|евт|аз|ов)[ая]$/
  .test(t.split(/[\s(]+/).filter(w => /^[а-яё-]+$/i.test(w)).pop() || '');

// латинские буквы-двойники в названиях РБК («прaведного») → кириллица, если слово кириллическое
const LAT = { a: 'а', e: 'е', o: 'о', p: 'р', c: 'с', x: 'х', y: 'у', k: 'к', A: 'А', B: 'В', E: 'Е', K: 'К', M: 'М', H: 'Н', O: 'О', P: 'Р', C: 'С', T: 'Т', X: 'Х' };
const norm = t => t.replace(/[А-Яа-яЁё]*[aeopcxykABEKMHOPCTX][A-Za-zА-Яа-яЁё]*/g, w => /[а-яё]/i.test(w) ? w.replace(/[aeopcxykABEKMHOPCTX]/g, c => LAT[c]) : w);

// 'official' | 'russia' | 'prof' | 'intl' | 'fun' | null (не берём: церковные и иностранные)
function classify(title) {
  const t = norm(title);
  if (OFFICIAL.test(t)) return 'official';
  if (RELIGIOUS.test(t)) return null;
  if (/ООН|ЮНЕСКО/.test(t) || (INTERNATIONAL.test(t) && !FOREIGN.test(t.replace(/Международный|Всемирный/g, '')))) return 'intl';
  if (FOREIGN.test(t) && !RUSSIA.test(t)) return null;
  if (RUSSIA.test(t)) return 'russia';
  if (/^День/.test(t) && (PROF.test(t) || profWord(t)) && !/рождения/.test(t)) return 'prof';
  return 'fun'; // шуточные и неофициальные: «День попкорна», «День человека-паука»
}

// страница РБК закрыта Qrator — читаем её настоящим Edge, данные лежат в __NEXT_DATA__
async function download(url = URL_RBC) {
  const { chromium } = require('playwright-core');
  const channel = process.env.BROWSER_CHANNEL ?? (process.platform === 'win32' ? 'msedge' : undefined); // на сервере — Chromium из playwright
  const b = await chromium.launch({ channel: channel || undefined, headless: true });
  try {
    const p = await b.newPage({ locale: 'ru-RU' });
    await p.goto(url, { waitUntil: 'domcontentloaded', timeout: 60000 });
    await p.waitForSelector('#__NEXT_DATA__', { state: 'attached', timeout: 30000 });
    return await p.evaluate(() => JSON.parse(document.getElementById('__NEXT_DATA__').textContent).props.pageProps.holidaysList
      .flatMap(d => d.holidaysList.map(h => ({ ts: d.dateTimeStamp, title: h.title }))));
  } finally { await b.close(); }
}

function build(raw) {
  const seen = new Set();
  return raw.map(h => ({ date: new Date(h.ts).toISOString().slice(0, 10), title: norm(h.title).trim(), kind: classify(h.title) }))
    .filter(h => h.kind && !seen.has(h.date + h.title) && seen.add(h.date + h.title));
}

if (require.main === module) {
  (async () => {
    const raw = await download(process.argv[2]);
    const items = build(raw);
    fs.writeFileSync(OUT, JSON.stringify({ source: process.argv[2] || URL_RBC, fetchedAt: new Date().toISOString(), items }, null, 1));
    const by = items.reduce((a, h) => (a[h.kind] = (a[h.kind] || 0) + 1, a), {});
    console.log(`Всего у РБК: ${raw.length}, взято: ${items.length}`, by, '→', OUT);
  })().catch(e => { console.error('Не удалось загрузить праздники:', e.message.split('\n')[0]); process.exit(1); });
}

module.exports = { classify, build, norm, OUT };
